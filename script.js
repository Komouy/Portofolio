  function applyTheme(theme, save = true) {
    const t = theme === 'dark' ? 'dark' : 'light';
    document.documentElement.setAttribute('data-theme', t);
    if (themeToggle) {
      themeToggle.setAttribute('aria-label', t === 'dark' ? 'Ganti ke mode terang' : 'Ganti ke mode gelap');
      themeToggle.setAttribute('title', t === 'dark' ? 'Mode terang' : 'Mode gelap');
    }
    if (save) { try { localStorage.setItem('portfolio_theme', t); } catch (e) {} }
  }
  let savedTheme = 'light';
  try { savedTheme = localStorage.getItem('portfolio_theme') || 'light'; } catch (e) {}
  if (!localStorage.getItem('portfolio_theme') && window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches) {
    savedTheme = 'dark';
  }
  applyTheme(savedTheme, false);
  if (themeToggle) {
    themeToggle.addEventListener('click', () => {
      const cur = document.documentElement.getAttribute('data-theme') === 'dark' ? 'dark' : 'light';
      applyTheme(cur === 'dark' ? 'light' : 'dark');
    });
  }

  function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('portfolio_lang', lang);
    document.documentElement.lang = lang;

    // update lang switch UI
    const langSwitch = document.getElementById('langSwitch');
    if (langSwitch) {
      langSwitch.setAttribute('data-lang', lang);
      langSwitch.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang-val') === lang);
      });
    }

    // fade transition for elements
    const els = document.querySelectorAll('[data-i18n], [data-i18n-ph]');
    els.forEach(el => el.classList.add('i18n-changing'));

    setTimeout(() => {
      els.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key && translations[lang][key]) {
          el.innerHTML = translations[lang][key];
        }
        const phKey = el.getAttribute('data-i18n-ph');
        if (phKey && translations[lang][phKey]) {
          el.setAttribute('placeholder', translations[lang][phKey]);
        }
        el.classList.remove('i18n-changing');
      });
    }, 200);
  }

